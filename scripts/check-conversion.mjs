import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
const browser = await chromium.launch({headless:true});
const context = await browser.newContext();
const page = await context.newPage();
const base = 'http://127.0.0.1:4321';
for (const width of [320,390,768,1440]) {
  await page.setViewportSize({width,height:900});
  await page.goto(base, {waitUntil:'networkidle'});
  await page.locator('.hero-copy .action-button').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  const cv = page.getByRole('link',{name:'Download my CV (PDF)', exact:true});
  assert(await cv.isVisible());
  const box = await cv.boundingBox();
  assert(box.y >= 0 && box.y + box.height < 900);
  const downloadPromise = page.waitForEvent('download');
  await cv.click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(),'Takunda-Maswi-CV.pdf');
  assert.equal(await download.failure(),null);
  await page.screenshot({path:`artifacts/conversion-${width}.png`});
  await page.goto(`${base}/contact/`,{waitUntil:'networkidle'});
  assert.equal(await page.locator('.enquiry-options .action-button').count(),3);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.screenshot({path:`artifacts/contact-${width}.png`,fullPage:true});
  const a11y = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();
  assert.deepEqual(a11y.violations.map(v=>v.id),[]);
}
await page.goto(`${base}/training/`);
assert.match(await page.locator('.page-intro .action-button').getAttribute('href'),/^mailto:/);
await page.goto(`${base}/work/svika/`);
assert.match(decodeURIComponent(await page.locator('main > .action-button').getAttribute('href')),/Svika/);
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto(base);
assert(await page.locator('.hero-copy .action-button').isVisible());
const pdf = await page.request.get(`${base}/Takunda-Maswi-CV.pdf`);
assert.equal(pdf.status(),200);
assert((await pdf.body()).subarray(0,4).toString()==='%PDF');
await browser.close();
console.log('PASS: 4 viewport widths, CV downloads, enquiry paths, reduced-motion CTA and served PDF. No emails sent.');
